const i18nElements = document.querySelectorAll("[data-i18n]");
const languageButtons = document.querySelectorAll("[data-lang-option]");
const descriptionMeta = document.querySelector('meta[name="description"]');
const ogTitleMeta = document.querySelector('meta[property="og:title"]');
const ogDescriptionMeta = document.querySelector('meta[property="og:description"]');
const twitterTitleMeta = document.querySelector('meta[name="twitter:title"]');
const twitterDescriptionMeta = document.querySelector('meta[name="twitter:description"]');

function setLanguage(language) {
  const lang = translations[language] ? language : "zh";
  const dictionary = translations[lang];

  document.documentElement.lang = lang === "zh" ? "zh-CN" : "en";
  document.documentElement.dataset.lang = lang;
  document.title = dictionary.metaTitle;

  if (descriptionMeta) descriptionMeta.content = dictionary.metaDescription;
  if (ogTitleMeta) ogTitleMeta.content = dictionary.metaTitle;
  if (ogDescriptionMeta) ogDescriptionMeta.content = dictionary.metaDescription;
  if (twitterTitleMeta) twitterTitleMeta.content = dictionary.metaTitle;
  if (twitterDescriptionMeta) twitterDescriptionMeta.content = dictionary.metaDescription;

  i18nElements.forEach((element) => {
    const key = element.dataset.i18n;
    if (dictionary[key]) {
      element.textContent = dictionary[key];
    }
  });

  languageButtons.forEach((button) => {
    const isActive = button.dataset.langOption === lang;
    button.setAttribute("aria-pressed", String(isActive));
  });

}

languageButtons.forEach((button) => {
  button.addEventListener("click", () => {
    setLanguage(button.dataset.langOption);
  });
});

setLanguage("zh");

const year = document.getElementById("year");
if (year) {
  year.textContent = String(new Date().getFullYear());
}
